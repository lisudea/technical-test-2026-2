CREATE TABLE tbl_usuario (
    id_usuario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo varchar(150) NOT NULL,
    password_hash varchar(255),
    google_sub varchar(255),
    nombres varchar(100) NOT NULL,
    apellidos varchar(100) NOT NULL,
    id_estado_usuario integer NOT NULL,
    id_idioma integer,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
    fecha_cambio_password timestamptz,
    ultimo_acceso timestamptz,

    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT uq_usuario_google_sub UNIQUE (google_sub),

    CONSTRAINT fk_usuario_estado_usuario
        FOREIGN KEY (id_estado_usuario)
        REFERENCES tbl_estado_usuario (id_estado_usuario)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_usuario_idioma
        FOREIGN KEY (id_idioma)
        REFERENCES tbl_idioma (id_idioma)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT ck_usuario_correo_normalizado
        CHECK (
            correo = lower(btrim(correo))
            AND correo ~ '^[^@[:space:]]+@[^@[:space:]]+$'
        ),

    CONSTRAINT ck_usuario_password_hash
        CHECK (
            password_hash IS NULL
            OR password_hash LIKE '$argon2id$%'
        ),

    CONSTRAINT ck_usuario_google_sub
        CHECK (
            google_sub IS NULL
            OR length(btrim(google_sub)) > 0
        ),

    CONSTRAINT ck_usuario_mecanismo_autenticacion
        CHECK (
            password_hash IS NOT NULL
            OR google_sub IS NOT NULL
        ),

    CONSTRAINT ck_usuario_nombres
        CHECK (length(btrim(nombres)) > 0),

    CONSTRAINT ck_usuario_apellidos
        CHECK (length(btrim(apellidos)) > 0)
);

