-- 01-estructura-sin-funciones.sql
-- Sistema de Gestión y Reservas de Equipos del LIS
-- PostgreSQL / Supabase
-- Versión simplificada y estable (sin funciones, triggers ni vistas)
--
-- IMPORTANTE:
--   1. Este archivo ELIMINA únicamente los objetos del proyecto SistemaReservasLIS
--      y los vuelve a crear desde cero.
--   2. No elimina el esquema public ni objetos internos de Supabase.
--   3. Está pensado para ejecutarse con el botón normal "Run".
--   4. RLS se habilita explícitamente al final; NO es necesario usar
--      "Run and enable RLS".
--
-- Qué conserva del modelo:
--   - 20 tablas.
--   - PK y FK.
--   - UNIQUE.
--   - CHECK.
--   - índices.
--   - integridad referencial.
--   - autenticación Google/local.
--   - sesiones/refresh token.
--   - recuperación de contraseña.
--   - inventario.
--   - reservas.
--   - configuración.
--   - auditoría.
--
-- Qué se deja deliberadamente al backend:
--   - Google SSO y validación real del token.
--   - validación del dominio usando tbl_configuracion.
--   - generación/verificación Argon2id.
--   - JWT.
--   - rotación de refresh token.
--   - recuperación de contraseña.
--   - asignación automática de rol base.
--   - disponibilidad derivada DISPONIBLE/RESERVADO.
--   - prevención transaccional de solapamientos.
--   - HTTP 409 Conflict.
--   - auditoría automática de acciones.
-- ============================================================================

