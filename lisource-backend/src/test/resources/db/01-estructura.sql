CREATE TABLE tbl_reserva (
    id_reserva bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_reserva varchar(40) NOT NULL,
    id_usuario bigint NOT NULL,
    id_estado_reserva integer NOT NULL,
    fecha_inicio timestamptz NOT NULL,
    fecha_fin timestamptz NOT NULL,
    observaciones text,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
    fecha_cancelacion timestamptz,
    id_usuario_cancelacion bigint,
    motivo_cancelacion text,

    CONSTRAINT uq_reserva_codigo UNIQUE (codigo_reserva),

    CONSTRAINT fk_reserva_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES tbl_usuario (id_usuario)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_reserva_estado
        FOREIGN KEY (id_estado_reserva)
        REFERENCES tbl_estado_reserva (id_estado_reserva)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_reserva_usuario_cancelacion
        FOREIGN KEY (id_usuario_cancelacion)
        REFERENCES tbl_usuario (id_usuario)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT ck_reserva_codigo
        CHECK (
            codigo_reserva = upper(btrim(codigo_reserva))
            AND length(btrim(codigo_reserva)) > 0
        ),

    CONSTRAINT ck_reserva_fechas
        CHECK (fecha_fin > fecha_inicio),

    CONSTRAINT ck_reserva_cancelacion
        CHECK (
            (
                fecha_cancelacion IS NULL
                AND id_usuario_cancelacion IS NULL
            )
            OR
            (
                fecha_cancelacion IS NOT NULL
                AND id_usuario_cancelacion IS NOT NULL
            )
        ),

    CONSTRAINT ck_reserva_motivo_cancelacion
        CHECK (
            motivo_cancelacion IS NULL
            OR length(btrim(motivo_cancelacion)) > 0
        )
);

CREATE INDEX idx_reserva_usuario
    ON tbl_reserva (id_usuario);

CREATE INDEX idx_reserva_estado
    ON tbl_reserva (id_estado_reserva);

CREATE INDEX idx_reserva_fecha_inicio
    ON tbl_reserva (fecha_inicio);

CREATE INDEX idx_reserva_fecha_fin
    ON tbl_reserva (fecha_fin);

