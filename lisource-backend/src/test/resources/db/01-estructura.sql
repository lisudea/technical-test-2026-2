CREATE TABLE tbl_sesion (
    id_sesion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario bigint NOT NULL,
    refresh_token_hash varchar(128) NOT NULL,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_expiracion timestamptz NOT NULL,
    fecha_ultimo_uso timestamptz,
    fecha_revocacion timestamptz,
    ip_origen varchar(45),
    user_agent varchar(500),

    CONSTRAINT uq_sesion_refresh_token_hash UNIQUE (refresh_token_hash),

    CONSTRAINT fk_sesion_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES tbl_usuario (id_usuario)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT ck_sesion_refresh_hash
        CHECK (
            refresh_token_hash = lower(refresh_token_hash)
            AND refresh_token_hash ~ '^[0-9a-f]{64}$'
        ),

    CONSTRAINT ck_sesion_expiracion
        CHECK (fecha_expiracion > fecha_creacion),

    CONSTRAINT ck_sesion_ultimo_uso
        CHECK (
            fecha_ultimo_uso IS NULL
            OR fecha_ultimo_uso >= fecha_creacion
        ),

    CONSTRAINT ck_sesion_revocacion
        CHECK (
            fecha_revocacion IS NULL
            OR fecha_revocacion >= fecha_creacion
        )
);

CREATE INDEX idx_sesion_usuario
    ON tbl_sesion (id_usuario);

CREATE INDEX idx_sesion_expiracion
    ON tbl_sesion (fecha_expiracion);

CREATE INDEX idx_sesion_usuario_expiracion
    ON tbl_sesion (id_usuario, fecha_expiracion DESC);

CREATE INDEX idx_sesion_activas_usuario
    ON tbl_sesion (id_usuario, fecha_expiracion DESC)
    WHERE fecha_revocacion IS NULL;


CREATE TABLE tbl_recuperacion_password (
    id_recuperacion_password bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario bigint NOT NULL,
    token_hash varchar(128) NOT NULL,
    fecha_solicitud timestamptz NOT NULL DEFAULT now(),
    fecha_expiracion timestamptz NOT NULL,
    fecha_uso timestamptz,
    fecha_revocacion timestamptz,
    ip_solicitud varchar(45),
    user_agent varchar(500),

    CONSTRAINT uq_recuperacion_password_token_hash UNIQUE (token_hash),

    CONSTRAINT fk_recuperacion_password_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES tbl_usuario (id_usuario)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT ck_recuperacion_password_hash
        CHECK (
            token_hash = lower(token_hash)
            AND token_hash ~ '^[0-9a-f]{64}$'
        ),

    CONSTRAINT ck_recuperacion_password_expiracion
        CHECK (fecha_expiracion > fecha_solicitud),

    CONSTRAINT ck_recuperacion_password_uso
        CHECK (
            fecha_uso IS NULL
            OR fecha_uso >= fecha_solicitud
        ),

    CONSTRAINT ck_recuperacion_password_revocacion
        CHECK (
            fecha_revocacion IS NULL
            OR fecha_revocacion >= fecha_solicitud
        ),

    CONSTRAINT ck_recuperacion_password_no_uso_y_revocacion
        CHECK (
            NOT (
                fecha_uso IS NOT NULL
                AND fecha_revocacion IS NOT NULL
            )
        )
);

CREATE INDEX idx_recuperacion_password_usuario
    ON tbl_recuperacion_password (id_usuario);

CREATE INDEX idx_recuperacion_password_usuario_fecha
    ON tbl_recuperacion_password (id_usuario, fecha_solicitud DESC);

CREATE INDEX idx_recuperacion_password_pendiente
    ON tbl_recuperacion_password (id_usuario, fecha_expiracion)
    WHERE fecha_uso IS NULL
      AND fecha_revocacion IS NULL;


